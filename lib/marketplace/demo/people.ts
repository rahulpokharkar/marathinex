import type { PersonProfile, RoleCode } from "../types";
import { createDemoProfileFields } from "./profile-fields";

function person(
  id: string,
  displayName: string,
  roleCodes: RoleCode | readonly RoleCode[],
  details: Omit<
    PersonProfile,
    | "id"
    | "kind"
    | "demo"
    | "verified"
    | "displayName"
    | "slug"
    | "headline"
    | "primaryRole"
    | "roles"
    | "portfolio"
    | "featured"
  > & { featured?: boolean },
): PersonProfile {
  const profileId = `demo-person-${id}`;
  const { featured, ...profileDetails } = details;

  return {
    id: profileId,
    kind: "person",
    displayName,
    ...createDemoProfileFields(profileId, displayName, roleCodes, featured),
    demo: true,
    verified: false,
    ...profileDetails,
  };
}

